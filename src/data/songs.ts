export const dhaakSongs = songs.filter((song) => song.category === "Dhaak");
export const regularSongs = songs.filter((song) => song.category !== "Dhaak");
export const longSongs = regularSongs.filter((song) => (song.durationSeconds ?? 0) > 600);
const playlistSongIds = [1, 2, 3, 13, 14, 15, 23, 45, 63, 76, 78];
export const playlistSongs = playlistSongIds
  .map((id) => songs.find((song) => song.id === id))
  .filter((song): song is Song => Boolean(song));

// Validate playlist for duplicate YouTube IDs
const seenIds = new Map<string, number[]>();
songs.forEach((song) => {
  const existing = seenIds.get(song.youtubeId) || [];
  existing.push(song.id);
  seenIds.set(song.youtubeId, existing);
});

export const duplicateIds: Record<string, number[]> = {};
seenIds.forEach((ids, ytId) => {
  if (ids.length > 1) {
    duplicateIds[ytId] = ids;
  }
});

// Known potentially invalid YouTube IDs
export const potentiallyInvalidIds: string[] = [];

export function getThumbnailUrl(youtubeId: string): string {
  return `https://img.youtube.com/vi/${youtubeId}/mqdefault.jpg`;
}

export function searchSongs(query: string): Song[] {
  const lower = query.toLowerCase();
  return songs.filter(
    (song) =>
      song.title.toLowerCase().includes(lower) ||
      song.artist.toLowerCase().includes(lower) ||
      song.category.toLowerCase().includes(lower)
  );
}
